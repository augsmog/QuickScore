#!/usr/bin/env python3
"""Execute real SQL drift, extract it, and require compare AND offline guard red."""
import argparse, json, os, pathlib, subprocess, sys, tempfile
from drift import HERE, load
p=argparse.ArgumentParser()
p.add_argument('--pgdata'); p.add_argument('--url')
# Platform-owned objects (auth.users, supabase_admin defaults) need the local platform owner role.
p.add_argument('--admin-url')
a=p.parse_args()
ADMIN={'trigger disabled','managed default revoke'}
def run(sql,admin=False):
    if a.pgdata:
        cmd=[os.environ.get('PGBIN','/usr/lib/postgresql/17/bin')+'/postgres','--single','-D',a.pgdata,'-j','postgres']
    else:
        cmd=['psql',(a.admin_url or a.url) if admin else a.url,'-X','-At','-v','ON_ERROR_STOP=1']
    r=subprocess.run(cmd,input=sql,text=True,capture_output=True)
    assert r.returncode==0 and 'ERROR:' not in r.stdout+r.stderr and 'FATAL:' not in r.stdout+r.stderr,r.stdout+r.stderr
    return r.stdout
probe=(HERE/'rls-probe.sql').read_text()
if a.pgdata:
    print('SKIP behavior probe: PostgreSQL single-user mode does not fire event triggers; required in pinned-stack CI')
else:
    run(probe)
    print('PASS event trigger enables RLS on probe table')
fixtures={
 'event removed':'DROP EVENT TRIGGER ensure_rls;',
 'event disabled':'ALTER EVENT TRIGGER ensure_rls DISABLE;',
 'identity mode':'ALTER TABLE public.golfcore_usage ALTER COLUMN id SET GENERATED BY DEFAULT;',
 'sequence cache':'ALTER SEQUENCE public.golfcore_usage_id_seq CACHE 2;',
 'sequence ownership':'ALTER TABLE public.golfcore_usage ALTER COLUMN id DROP IDENTITY; CREATE SEQUENCE public.golfcore_usage_id_seq AS bigint OWNED BY public.golfcore_usage.id;',
 'view reloptions':'ALTER VIEW public.channel_effectiveness SET (security_invoker=true);',
 'schema grant':'GRANT CREATE ON SCHEMA public TO anon;',
 'column ACL':'GRANT SELECT (id) ON public.contests TO anon;',
 'trigger disabled':'ALTER TABLE auth.users DISABLE TRIGGER on_auth_user_created;',
 'trigger replica':'ALTER TABLE public.contests ENABLE REPLICA TRIGGER contests_updated_at;',
 'global table default':'ALTER DEFAULT PRIVILEGES FOR ROLE postgres GRANT SELECT ON TABLES TO anon;',
 'global function default':'ALTER DEFAULT PRIVILEGES FOR ROLE postgres GRANT EXECUTE ON FUNCTIONS TO anon;',
 'global function revoke':'ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;',
 'public default revoke':'ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE SELECT ON TABLES FROM anon;',
 'managed default revoke':'ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public REVOKE SELECT ON TABLES FROM anon;',
}
for name,sql in fixtures.items():
    out=run('BEGIN;\n\n'+sql+'\n\n'+(HERE/'catalog-query.sql').read_text()+'\n\nROLLBACK;\n',admin=name in ADMIN)
    if a.pgdata:out=out.split('catalog = "',1)[1]
    else:out=next(line for line in out.splitlines() if line.startswith('{'))
    raw,_=json.JSONDecoder().raw_decode(out)
    # Guard is a live-ledger gate; isolate the schema mutation from local ledger.
    raw['migrations']=load(HERE/'expected-ledger.json')
    with tempfile.TemporaryDirectory() as d:
        f=pathlib.Path(d)/'mutation.json'; f.write_text(json.dumps(raw))
        c=subprocess.run([sys.executable,str(HERE/'drift.py'),'compare',str(HERE.parent/'schema-snapshot/live.json'),str(f)],capture_output=True,text=True)
        g=subprocess.run(['bash',str(HERE/'preapply-check.sh'),str(f)],capture_output=True,text=True)
        assert c.returncode==1 and 'live/' in c.stdout,(name,c)
        assert g.returncode!=0 and 'supabase migration repair' not in g.stdout,(name,g)
    print('PASS SQL compare + preapply rejection: '+name)

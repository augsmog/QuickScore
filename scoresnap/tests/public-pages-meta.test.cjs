const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const root = path.resolve(__dirname,'..');
const crypto = require('node:crypto');
// SHA-256 of body HTML and headers extracted from reviewed main 501bdae.
// Pinned digests also work in shallow CI checkouts.
const baseline = {"site/index.html": "1629c5195b87c8a6ad8b21a3ed9a92c3a7eb62dcd43dde29465c09e5efc0c730", "site/support/index.html": "cc9605e264300ca136bdac55772a795570366da0c39e67dc5e8945d28854d746", "site/privacy/index.html": "46f6abeb46370043f6b9184b03d19059ffaf1beb1ade2190068a8efef390b7e2", "site/terms/index.html": "c40452d9f332c61ae6655e39248b6495c4b5020986f8dc19c6fb2612c0af7e2f"};
const digest = text => crypto.createHash('sha256').update(text).digest('hex');
const routes = ['', 'support','privacy','terms'];
const file = route => `site/${route ? route+'/' : ''}index.html`;
const read = rel => fs.readFileSync(path.join(root,rel),'utf8');
for(const route of routes) test(`public metadata and unchanged body: /${route}`,()=>{
  const html=read(file(route)), url=`https://snapscore.autumn8.me/${route}`;
  const title=html.match(/<title>(.*?)<\/title>/)[1];
  expect(html).toContain(`<link rel="canonical" href="${url}">`);
  for(const [key,value] of [['type','website'],['url',url],['site_name','SnapScore'],['title',title]])
    expect(html).toContain(`<meta property="og:${key}" content="${value}">`);
  expect(html).toContain('<meta name="twitter:card" content="summary">');
  expect(html).not.toMatch(/(?:name|property)="(?:description|og:description|og:image|twitter:image)"/);
  expect(digest(html.match(/<body>[\s\S]*<\/body>/)[0])).toBe(baseline[file(route)]);
});
test('crawl artifacts list exactly the public routes and generated bytes are reproducible',()=>{
  const urls=routes.map(route=>`https://snapscore.autumn8.me/${route}`);
  expect(read('site/robots.txt')).toBe('User-agent: *\nAllow: /\nSitemap: https://snapscore.autumn8.me/sitemap.xml\n');
  expect([...read('site/sitemap.xml').matchAll(/<loc>(.*?)<\/loc>/g)].map(m=>m[1])).toEqual(urls);
  const artifacts=[...routes.map(file),'site/robots.txt','site/sitemap.xml','site/_headers'];
  const before=artifacts.map(read);
  cp.execFileSync(process.execPath,['scripts/build-public-pages.mjs'],{cwd:root});
  expect(artifacts.map(read)).toEqual(before);
  expect(digest(read('site/_headers'))).toBe('faef8de71ecb980437c85c31a31ce0ba0b2bf6982e7329bdd64d2a22cafc31c9');
});
